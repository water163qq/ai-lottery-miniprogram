#!/usr/bin/env python3
"""Sync shared lottery core modules from the Web/Android app repository.

The main app repository owns the canonical ES module sources. This script
fetches them (from a local checkout or over HTTP) and rewrites the module
syntax to CommonJS so the Mini Program can require() them directly.

Usage:
    python3 scripts/sync-from-app-repo.py
    python3 scripts/sync-from-app-repo.py --src ../ai-lottery/lottery-ai/js
    python3 scripts/sync-from-app-repo.py --base-url https://raw.githubusercontent.com/water163qq/ai-lottery/master/lottery-ai/js
"""

import argparse
import gzip
import pathlib
import re
import sys
import urllib.request

DEFAULT_BASE_URL = (
    "https://raw.githubusercontent.com/water163qq/ai-lottery/master/lottery-ai/js"
)

HEADER = "/* Auto-generated by scripts/sync-from-app-repo.py. Do not edit by hand. */\n"

REWRITES = {
    "data.js": [
        (r"import \{ LIVE_DATA \} from './livedata.js';",
         "const { LIVE_DATA } = require('./livedata.js');"),
        (r"export \{ GAME, HISTORY, DATA_META, mulberry32 \};",
         "module.exports = { GAME, HISTORY, DATA_META, mulberry32 };"),
    ],
    "engine.js": [
        (r"import \{ GAME, HISTORY, mulberry32 \} from './data.js';",
         "const { GAME, HISTORY, mulberry32 } = require('./data.js');"),
        (r"export \{ analyze, generatePick, prizeInfo \};",
         "module.exports = { analyze, generatePick, prizeInfo };"),
    ],
    "livedata.js": [
        (r"export \{ LIVE_DATA \};",
         "module.exports = { LIVE_DATA };"),
    ],
}

MIN_DRAWS = 20


def http_get(url, timeout=60):
    req = urllib.request.Request(url, headers={
        "User-Agent": "ai-lottery-miniprogram-sync/1.0",
        "Accept": "text/plain, */*",
        "Accept-Encoding": "gzip",
    })
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        raw = resp.read()
        if resp.headers.get("Content-Encoding") == "gzip":
            raw = gzip.decompress(raw)
    return raw.decode("utf-8", errors="replace")


def read_source(name, src, base_url):
    if src:
        path = pathlib.Path(src) / name
        if not path.exists():
            raise SystemExit(f"missing source file: {path}")
        return path.read_text(encoding="utf-8")
    return http_get(base_url.rstrip("/") + "/" + name)


def convert(name, text):
    for pattern, replacement in REWRITES[name]:
        text, count = re.subn(pattern, replacement, text)
        if count != 1:
            raise SystemExit(f"rewrite failed for {name}: {pattern!r} matched {count} times")
    if "module.exports" not in text:
        raise SystemExit(f"{name}: conversion produced no module.exports")
    if re.search(r"^\s*(import|export)\s", text, re.M):
        raise SystemExit(f"{name}: leftover ES module syntax")
    return HEADER + text


def validate_livedata(text):
    match = re.search(r"const LIVE_DATA = (\{.*?\});\n\nmodule\.exports", text, re.S)
    if not match:
        raise SystemExit("livedata.js: LIVE_DATA payload not found")
    import json
    data = json.loads(match.group(1))
    draws = data.get("draws") or {}
    for game in ("ssq", "dlt"):
        rows = draws.get(game) or []
        if len(rows) < MIN_DRAWS:
            raise SystemExit(f"livedata.js: {game} has only {len(rows)} draws (<{MIN_DRAWS})")
        issues = [str(d.get("issue", "")) for d in rows]
        if issues != sorted(issues, reverse=True):
            raise SystemExit(f"livedata.js: {game} draws are not sorted descending")
        for row in rows[:5]:
            areas = row.get("areas") or {}
            if not areas:
                raise SystemExit(f"livedata.js: {game} draw {row.get('issue')} has no areas")
    return data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", help="local directory holding lottery-ai/js")
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL)
    parser.add_argument("--out", default="utils")
    args = parser.parse_args()

    out_dir = pathlib.Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    converted = {}
    for name in ("livedata.js", "data.js", "engine.js"):
        source = read_source(name, args.src, args.base_url)
        converted[name] = convert(name, source)

    data = validate_livedata(converted["livedata.js"])

    for name, text in converted.items():
        target = out_dir / name
        if target.exists() and target.read_text(encoding="utf-8") == text:
            print(f"unchanged {target}")
            continue
        target.write_text(text, encoding="utf-8")
        print(f"wrote {target}")

    updated = data.get("updatedAt", "unknown")
    news_count = len(data.get("news") or [])
    print(f"data updatedAt={updated} news={news_count}")
    for game in ("ssq", "dlt"):
        rows = (data.get("draws") or {}).get(game) or []
        print(f"{game}: {len(rows)} draws, latest {rows[0]['issue']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
